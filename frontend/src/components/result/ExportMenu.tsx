import { useEffect, useRef, useState } from 'react'

import { getCalendarUrl } from '@/api/calendar'
import { exportGuideDocx } from '@/api/guide'
import { useAuthStore } from '@/store/authStore'
import type { CalendarUrlResponse } from '@/types'

interface ExportMenuProps {
  containerRef: React.RefObject<HTMLDivElement | null>
  guideId: string
}

interface GuideEvent {
  taskName: string
  timeHint: string
  stepsText: string
}

function collectEvents(container: HTMLDivElement | null): GuideEvent[] {
  if (!container) return []
  const events: GuideEvent[] = []
  container.querySelectorAll('table').forEach((table) => {
    table.querySelectorAll('tbody tr').forEach((row) => {
      const cells = row.querySelectorAll('td')
      if (cells.length < 1) return
      events.push({
        taskName: cells[0]?.innerText.trim() || 'Study Task',
        timeHint: cells[1]?.innerText.trim() || '',
        stepsText: cells[cells.length - 1]?.innerText.trim() || '',
      })
    })
  })
  return events
}

function buildPrintDocument(tablesHtml: string): string {
  return (
    '<!DOCTYPE html><html><head><meta charset="UTF-8"><title>AAF Study Plan</title>' +
    '<style>' +
    'body{font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif;padding:40px;color:#2b2b2b;background:#fff}' +
    'h1{font-size:22px;color:#86351C;margin-bottom:20px;border-bottom:2px solid #86351C;padding-bottom:10px}' +
    'table{width:100%;border-collapse:collapse;margin-bottom:30px;font-size:12.5px;page-break-inside:avoid}' +
    'th{background:#f4f1ea;color:#86351C;font-weight:700;padding:11px 12px;text-align:left;border-bottom:2px solid #86351C;font-size:12px}' +
    'td{padding:11px 12px;border-bottom:1px solid #d8d3c5;vertical-align:top;line-height:1.65}' +
    'tr:nth-child(even) td{background:#fafaf8}' +
    'footer{margin-top:40px;font-size:10px;color:#aaa;text-align:center}' +
    '@media print{body{padding:20px}}' +
    '</style></head><body>' +
    '<h1>🐜 AAF — Your Study Battle Plan</h1>' +
    tablesHtml +
    '<footer>Generated by AAF (Anteater Acing the Future)</footer>' +
    '<script>' +
    'window.onload=function(){' +
    'window.print();' +
    'window.onafterprint=function(){window.close();};' +
    '};' +
    '</script>' +
    '</body></html>'
  )
}

function tablesOuterHtml(container: HTMLDivElement | null): string {
  if (!container) return ''
  let html = ''
  container.querySelectorAll('table').forEach((t) => {
    html += t.outerHTML
  })
  return html
}

export function ExportMenu({ containerRef, guideId }: ExportMenuProps) {
  const accessToken = useAuthStore((s) => s.accessToken)

  const [open, setOpen] = useState(false)
  const [pdfBlocked, setPdfBlocked] = useState(false)
  const [shareCopied, setShareCopied] = useState(false)
  const wrapRef = useRef<HTMLDivElement>(null)

  const [calendarOpen, setCalendarOpen] = useState(false)
  const [calendarLoading, setCalendarLoading] = useState(false)
  const [calendarError, setCalendarError] = useState(false)
  const [calendarUrls, setCalendarUrls] = useState<CalendarUrlResponse | null>(null)
  const [calendarCopied, setCalendarCopied] = useState(false)

  const [docxState, setDocxState] = useState<'idle' | 'loading' | 'error'>('idle')

  useEffect(() => {
    function handleClickOutside(e: MouseEvent) {
      if (wrapRef.current && !wrapRef.current.contains(e.target as Node)) {
        setOpen(false)
        setCalendarOpen(false)
      }
    }
    document.addEventListener('click', handleClickOutside)
    return () => document.removeEventListener('click', handleClickOutside)
  }, [])

  async function handleToggleCalendar() {
    const willOpen = !calendarOpen
    setCalendarOpen(willOpen)
    if (willOpen && !calendarUrls && accessToken) {
      setCalendarLoading(true)
      setCalendarError(false)
      try {
        setCalendarUrls(await getCalendarUrl())
      } catch {
        setCalendarError(true)
      } finally {
        setCalendarLoading(false)
      }
    }
  }

  async function handleCopyCalendarLink() {
    if (!calendarUrls) return
    try {
      await navigator.clipboard.writeText(calendarUrls.ics_url)
      setCalendarCopied(true)
      setTimeout(() => setCalendarCopied(false), 1800)
    } catch {
      // clipboard unavailable — silently ignore, matching Share's existing pattern
    }
  }

  function handleDownloadPdf() {
    setOpen(false)
    const html = buildPrintDocument(tablesOuterHtml(containerRef.current))
    const blob = new Blob([html], { type: 'text/html;charset=utf-8' })
    const blobUrl = URL.createObjectURL(blob)
    const win = window.open(blobUrl, '_blank')

    if (!win) {
      setPdfBlocked(true)
      setTimeout(() => setPdfBlocked(false), 3000)
    }
    setTimeout(() => URL.revokeObjectURL(blobUrl), 10000)
  }

  async function handleExportDocs() {
    setDocxState('loading')
    try {
      const { download_url } = await exportGuideDocx(guideId)
      window.open(download_url, '_blank')
      setDocxState('idle')
      setOpen(false)
    } catch {
      setDocxState('error')
      setTimeout(() => setDocxState('idle'), 3200)
    }
  }

  async function handleShare() {
    setOpen(false)
    const events = collectEvents(containerRef.current)
    const shareText = events.map((ev) => `📌 ${ev.taskName}${ev.timeHint ? `\n⏱ ${ev.timeHint}` : ''}`).join('\n\n')

    if (navigator.share) {
      try {
        await navigator.share({ title: 'My AAF Study Plan', text: shareText, url: window.location.href })
        return
      } catch (err) {
        if (err instanceof Error && err.name === 'AbortError') return
      }
    }
    try {
      await navigator.clipboard.writeText(`${shareText}\n\n${window.location.href}`)
      setShareCopied(true)
      setTimeout(() => setShareCopied(false), 1800)
    } catch {
      // clipboard unavailable — silently ignore, matching original's no-op catch
    }
  }

  return (
    <div className="section-action-wrap" ref={wrapRef}>
      <button type="button" className="row-trigger section-trigger" title="More options" onClick={() => setOpen((o) => !o)}>
        more...
      </button>
      <div className={`row-popover${open ? ' open' : ''}`}>
        <button type="button" className="popover-item" onClick={handleToggleCalendar}>
          <span className="popover-item-icon">📅</span> Subscribe to Calendar
        </button>
        {calendarOpen && (
          <div className="px-1 pb-1">
            {!accessToken ? (
              <p className="px-3 py-2 text-[13px] text-[var(--ink-black)] opacity-60">Log in to subscribe to your calendar feed.</p>
            ) : calendarLoading ? (
              <p className="px-3 py-2 text-[13px] text-[var(--ink-black)] opacity-60">Loading…</p>
            ) : calendarError ? (
              <p className="px-3 py-2 text-[13px] text-[var(--ink-black)] opacity-60">Couldn't load link — try again.</p>
            ) : calendarUrls ? (
              <>
                <button type="button" className="popover-item" onClick={handleCopyCalendarLink}>
                  <span className="popover-item-icon">{calendarCopied ? '✅' : '🔗'}</span>{' '}
                  {calendarCopied ? 'Copied!' : 'Copy Link'}
                </button>
                <a
                  className="popover-item"
                  href={`https://calendar.google.com/calendar/render?cid=${encodeURIComponent(calendarUrls.ics_url)}`}
                  target="_blank"
                  rel="noreferrer"
                >
                  <span className="popover-item-icon">🗓</span> Subscribe in Google Calendar
                </a>
                <a className="popover-item" href={calendarUrls.webcal_url}>
                  <span className="popover-item-icon">📅 </span> Subscribe in Apple Calendar
                </a>
              </>
            ) : null}
          </div>
        )}
        <div className="popover-divider" />
        <button type="button" className="popover-item" onClick={handleDownloadPdf}>
          {pdfBlocked ? (
            <>
              <span className="popover-item-icon">⚠️</span> Allow pop-ups → retry
            </>
          ) : (
            <>
              <span className="popover-item-icon">📄</span> Download as PDF
            </>
          )}
        </button>
        <div className="popover-divider" />
        <button type="button" className="popover-item" onClick={handleExportDocs} disabled={docxState === 'loading'}>
          {docxState === 'loading' ? (
            <>
              <span className="popover-item-icon">⏳</span> Generating…
            </>
          ) : docxState === 'error' ? (
            <>
              <span className="popover-item-icon">⚠️</span> Failed — try again
            </>
          ) : (
            <>
              <span className="popover-item-icon">📝</span> Download as Word (.docx)
            </>
          )}
        </button>
        <div className="popover-divider" />
        <button type="button" className="popover-item" onClick={handleShare}>
          {shareCopied ? (
            <>
              <span className="popover-item-icon">✅</span> Copied!
            </>
          ) : (
            <>
              <span className="popover-item-icon">↗</span> Share
            </>
          )}
        </button>
      </div>
    </div>
  )
}
